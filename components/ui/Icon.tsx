/**
 * An icon sized by font size (1em), so the text-* classes that sized the old icon font
 * still size it, and colored by currentColor. Decorative unless given an aria-label.
 */
export default function Icon({
  name,
  className = '',
  ...rest
}: { name: string; className?: string } & Omit<React.SVGProps<SVGSVGElement>, 'name' | 'ref'>) {
  const Svg = ICONS[name];
  if (!Svg) return null;
  return <Svg size="1em" strokeWidth={1.75} aria-hidden={rest['aria-label'] ? undefined : true} className={`ui-icon ${className}`.trim()} {...rest} />;
}
